//! Reference glyphs of the EXP font, as greyscale ASCII art. Each is 13 columns
//! centred on the glyph's centre of brightness; the levels " .:-=+*#%@" are ink
//! 0/9 … 9/9. The game draws this font anti-aliased at fractional positions, so a
//! digit's pixels shift with where it lands; centring removes that shift.
//!
//! Built 2026-10-16 by averaging ~7,600 centred glyphs from a 10-minute recording
//! of the EXP readout at 1920x1080 (`glyph-collect record`).

